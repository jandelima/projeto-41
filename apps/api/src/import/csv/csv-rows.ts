/**
 * Parser de CSV compartilhado.
 *
 * Morava privado em `export/operations-csv.ts`; o leitor de extrato da fase 6
 * precisa do mesmo tratamento de aspas e de quebra de linha dentro de campo, e
 * duas copias de parser de CSV no mesmo repositorio divergem na primeira
 * correcao. O unico acrescimo e o delimitador, porque banco brasileiro usa `;`
 * tanto quanto `,`.
 */
export function parseCsvRows(text: string, delimiter = ","): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let inQuotes = false;

  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    if (inQuotes) {
      if (char === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 1;
        } else {
          inQuotes = false;
        }
      } else {
        field += char;
      }
      continue;
    }
    if (char === '"') {
      inQuotes = true;
    } else if (char === delimiter) {
      row.push(field);
      field = "";
    } else if (char === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (char !== "\r") {
      field += char;
    }
  }
  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}
